/*ToDo:Recomendación de Diseño para Proyectos Ambientales

En páginas de proyectos colaborativos, es muy útil añadir un pequeño distintivo o 
"badge" cuando el que responde es el autor del proyecto.

Puedes lograrlo comparando el nombre del autor del comentario con el nombre del autor del proyecto:

    1.Comentario normal: Borde gris, fondo blanco.

    2.Respuesta del Autor: Borde verde hoja, etiqueta que diga "Autor" junto al nombre.

Esto genera mucha confianza en la comunidad agroecológica porque saben que el experto está 
validando las dudas.
*/
